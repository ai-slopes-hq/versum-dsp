#[test]
fn rng_matches_js_mulberry32() {
    for (seed, vals) in REF {
        let mut r = Rng::new(seed);
        for (i, v) in vals.iter().enumerate() {
            assert!(r.next_f64() == *v, "seed {seed:#x} index {i}");
        }
    }
}

#[test]
fn rng_u32_is_float_times_2_pow_32() {
    let mut a = Rng::new(0xDEAD_BEEF);
    let mut b = Rng::new(0xDEAD_BEEF);
    for _ in 0..16 {
        assert_eq!(a.next_f64() * 4294967296.0, b.next_u32() as f64);
    }
}
